#!/usr/bin/env python3
"""Generate native-size, 1-bit UI font strikes for the e-paper firmware."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


# Every size used by production UI plus a continuous 12–24 px hardware test
# range. A caller requesting another size resolves to the closest strike; the
# renderer never scales a bitmap at runtime.
DEFAULT_SIZES = tuple(range(12, 25)) + (28, 35, 42, 49, 52, 56, 70)


def ui_characters(source_root: Path) -> list[str]:
    result: set[str] = {chr(codepoint) for codepoint in range(0x20, 0x7F)}
    for pattern in ("*.cpp", "*.h"):
        for path in source_root.rglob(pattern):
            text = path.read_text(encoding="utf-8")
            for literal in re.findall(r'"(?:\\.|[^"\\])*"', text):
                result.update(char for char in literal if ord(char) > 0x7F)
    return sorted(result, key=ord)


def rasterize(
    font: ImageFont.FreeTypeFont, character: str, threshold: int
) -> tuple[int, int, int, int, int, bytes]:
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    width = max(0, right - left)
    height = max(0, bottom - top)
    advance = max(1, min(255, round(font.getlength(character))))
    if width == 0 or height == 0:
        return width, height, left, top, advance, b""

    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    draw.text((-left, -top), character, font=font, fill=255, anchor="ls")
    stride = (width + 7) // 8
    bitmap = bytearray(stride * height)
    for y_pos in range(height):
        for x_pos in range(width):
            if image.getpixel((x_pos, y_pos)) >= threshold:
                bitmap[y_pos * stride + x_pos // 8] |= 0x80 >> (x_pos & 7)
    return width, height, left, top, advance, bytes(bitmap)


def cpp_bytes(data: bytes) -> list[str]:
    if not data:
        return ["    0x00U,"]
    rows: list[str] = []
    for offset in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02X}U" for value in data[offset : offset + 16])
        rows.append(f"    {values},")
    return rows


def generate(
    font_path: Path,
    regular_font_index: int,
    medium_font_index: int,
    small_regular_font_index: int,
    small_regular_max_size: int,
    small_regular_threshold: int,
    source_root: Path,
    output: Path,
    sizes: tuple[int, ...],
    regular_threshold: int,
    medium_threshold: int,
) -> None:
    characters = ui_characters(source_root)
    lines = [
        "// Generated by tools/generate_chinese_font_assets.py. Do not edit.",
        "// E-paper optical policy: Regular strikes at or below "
        f"{small_regular_max_size}px use TTC face {small_regular_font_index} "
        f"at threshold {small_regular_threshold} to protect fine strokes.",
        '#include "chinese_font_assets.h"',
        "",
        "#include <algorithm>",
        "#include <iterator>",
        "",
        "namespace {",
        "",
    ]
    strike_names: dict[str, list[str]] = {"Regular": [], "Medium": []}
    faces = (
        ("Regular", regular_font_index, regular_threshold),
        ("Medium", medium_font_index, medium_threshold),
    )
    for face_name, font_index, threshold in faces:
        for pixel_size in sizes:
            strike_font_index = font_index
            strike_threshold = threshold
            if face_name == "Regular" and pixel_size <= small_regular_max_size:
                # W3 body glyphs at 12–18px contain many one-pixel strokes.
                # They look acceptable in a desktop bitmap but lose segments on
                # the physical SSD1677 panel. Use the heavier source outline with
                # a stricter threshold to retain open counters while giving the
                # final 1-bit glyph enough optical weight.
                strike_font_index = small_regular_font_index
                strike_threshold = small_regular_threshold
            font = ImageFont.truetype(
                str(font_path), pixel_size, index=strike_font_index
            )
            ascent, descent = font.getmetrics()
            stem = f"k{face_name}{pixel_size}"
            glyph_lines: list[str] = []
            bitmap = bytearray()
            for character in characters:
                width, height, bearing_x, bearing_y, advance, glyph_bitmap = rasterize(
                    font, character, strike_threshold
                )
                offset = len(bitmap)
                bitmap.extend(glyph_bitmap)
                glyph_lines.append(
                    f"    {{0x{ord(character):04X}U, {offset}U, {width}U, {height}U, "
                    f"{bearing_x}, {bearing_y}, {advance}U}},  // U+{ord(character):04X}"
                )
            lines.append(f"constexpr ChineseFontGlyph {stem}Glyphs[] = {{")
            lines.extend(glyph_lines)
            lines.extend(["};", ""])
            lines.append(f"constexpr uint8_t {stem}Bitmap[] = {{")
            lines.extend(cpp_bytes(bytes(bitmap)))
            lines.extend(["};", ""])
            strike_name = f"{stem}Strike"
            lines.append(
                f"constexpr ChineseFontStrike {strike_name} = "
                f"{{{pixel_size}U, {ascent}U, {descent}U, {stem}Glyphs, "
                f"std::size({stem}Glyphs), {stem}Bitmap}};"
            )
            lines.append("")
            strike_names[face_name].append(strike_name)

    for face_name in ("Regular", "Medium"):
        lines.append(f"constexpr const ChineseFontStrike *k{face_name}Strikes[] = {{")
        lines.extend(f"    &{name}," for name in strike_names[face_name])
        lines.extend(["};", ""])

    lines.extend(
        [
            "}  // namespace",
            "",
            "const ChineseFontStrike &chinese_font_strike(uint8_t pixel_size,",
            "                                                FontWeight weight)",
            "{",
            "    const ChineseFontStrike *const *strikes =",
            "        weight == FontWeight::Regular ? kRegularStrikes : kMediumStrikes;",
            "    constexpr size_t count = std::size(kRegularStrikes);",
            "    size_t best = 0U;",
            "    unsigned best_distance = 255U;",
            "    for (size_t index = 0U; index < count; ++index) {",
            "        const unsigned size = strikes[index]->pixel_size;",
            "        const unsigned distance = size > pixel_size ? size - pixel_size",
            "                                                     : pixel_size - size;",
            "        if (distance < best_distance) {",
            "            best = index;",
            "            best_distance = distance;",
            "        }",
            "    }",
            "    return *strikes[best];",
            "}",
            "",
            "const ChineseFontGlyph *chinese_font_glyph(",
            "    const ChineseFontStrike &strike, uint32_t codepoint)",
            "{",
            "    const auto found = std::lower_bound(",
            "        strike.glyphs, strike.glyphs + strike.glyph_count, codepoint,",
            "        [](const ChineseFontGlyph &glyph, uint32_t value) {",
            "            return glyph.codepoint < value;",
            "        });",
            "    return found != strike.glyphs + strike.glyph_count &&",
            "                   found->codepoint == codepoint",
            "               ? found",
            "               : nullptr;",
            "}",
            "",
            "size_t chinese_font_glyph_count()",
            "{",
            "    return kRegularStrikes[0]->glyph_count;",
            "}",
            "",
        ]
    )
    output.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"generated {len(characters)} glyphs x {len(sizes)} sizes x 2 weights at {output}"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--source-root", type=Path, default=Path("src"))
    parser.add_argument("--regular-font-index", type=int, default=0)
    parser.add_argument("--medium-font-index", type=int, default=2)
    parser.add_argument("--small-regular-font-index", type=int, default=2)
    parser.add_argument("--small-regular-max-size", type=int, default=18)
    parser.add_argument("--small-regular-threshold", type=int, default=176)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/ui/assets/chinese_font_assets.cpp"),
    )
    parser.add_argument(
        "--sizes",
        default=",".join(str(size) for size in DEFAULT_SIZES),
        help="comma-separated native strike sizes",
    )
    parser.add_argument("--regular-threshold", type=int, default=128)
    parser.add_argument("--medium-threshold", type=int, default=144)
    args = parser.parse_args()
    sizes = tuple(sorted({int(value) for value in args.sizes.split(",")}))
    if not sizes or any(size < 1 or size > 255 for size in sizes):
        parser.error("--sizes must contain values from 1 to 255")
    if not 0 <= args.regular_threshold <= 255:
        parser.error("--regular-threshold must be between 0 and 255")
    if not 0 <= args.medium_threshold <= 255:
        parser.error("--medium-threshold must be between 0 and 255")
    if not 0 <= args.small_regular_threshold <= 255:
        parser.error("--small-regular-threshold must be between 0 and 255")
    if not 0 <= args.small_regular_max_size <= 255:
        parser.error("--small-regular-max-size must be between 0 and 255")
    generate(
        args.font,
        args.regular_font_index,
        args.medium_font_index,
        args.small_regular_font_index,
        args.small_regular_max_size,
        args.small_regular_threshold,
        args.source_root,
        args.output,
        sizes,
        args.regular_threshold,
        args.medium_threshold,
    )


if __name__ == "__main__":
    main()
