#!/usr/bin/env python3
"""Generate bounded 18/24 px GB2312 Level-1 input font strikes."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


EXPECTED_FONT_SHA256 = (
    "7633f5a016d4dd95e685a69633d818aabc4644c4b08e26bd35b1b30c45ed5dda"
)
INPUT_SIZES = (18, 24)
GLYPH_STRUCT_BYTES = 16
COMMON_INPUT_PUNCTUATION = "，。！？；：、“”‘’（）《》【】…—·"
MISSING_GLYPH_MARKER = "□"


def gb2312_level1_characters() -> list[str]:
    characters: set[str] = {chr(codepoint) for codepoint in range(0x20, 0x7F)}
    han_count = 0
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                character = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            characters.add(character)
            han_count += 1
    characters.update(COMMON_INPUT_PUNCTUATION)
    characters.add(MISSING_GLYPH_MARKER)
    if han_count != 3755 or len(characters) != 3871:
        raise ValueError(
            f"unexpected input coverage: han={han_count} total={len(characters)}"
        )
    return sorted(characters, key=ord)


def font_signature(font: ImageFont.FreeTypeFont, character: str) -> tuple[object, ...]:
    return (
        font.getbbox(character, anchor="ls"),
        round(font.getlength(character)),
        bytes(font.getmask(character, mode="L")),
    )


def rasterize(
    font: ImageFont.FreeTypeFont, character: str, threshold: int
) -> tuple[int, int, int, int, int, bytes]:
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    width = max(0, right - left)
    height = max(0, bottom - top)
    advance = max(1, min(255, round(font.getlength(character))))
    if width == 0 or height == 0:
        return width, height, left, top, advance, b""
    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    draw.text((-left, -top), character, font=font, fill=255, anchor="ls")
    stride = (width + 7) // 8
    bitmap = bytearray(stride * height)
    for y_pos in range(height):
        for x_pos in range(width):
            if image.getpixel((x_pos, y_pos)) >= threshold:
                bitmap[y_pos * stride + x_pos // 8] |= 0x80 >> (x_pos & 7)
    return width, height, left, top, advance, bytes(bitmap)


def rasterize_missing_marker(pixel_size: int) -> tuple[int, int, int, int, int, bytes]:
    """Return a crisp box-with-X marker that survives 1-bit e-paper output."""
    width = max(8, pixel_size - 4)
    height = width
    stride = (width + 7) // 8
    bitmap = bytearray(stride * height)
    for y_pos in range(height):
        for x_pos in range(width):
            border = x_pos in (0, width - 1) or y_pos in (0, height - 1)
            diagonal = x_pos == y_pos or x_pos + y_pos == width - 1
            if border or diagonal:
                bitmap[y_pos * stride + x_pos // 8] |= 0x80 >> (x_pos & 7)
    return width, height, 2, -(height + 1), pixel_size, bytes(bitmap)


def cpp_bytes(data: bytes) -> list[str]:
    rows: list[str] = []
    for offset in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02X}U" for value in data[offset : offset + 16])
        rows.append(f"    {values},")
    return rows or ["    0x00U,"]


def generate(font_path: Path, output: Path, threshold: int) -> None:
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    if digest != EXPECTED_FONT_SHA256:
        raise ValueError(f"font SHA-256 mismatch: {digest}")
    characters = gb2312_level1_characters()
    lines = [
        "// Generated by tools/generate_chinese_input_font_assets.py. Do not edit.",
        '#include "chinese_input_font_assets.h"',
        "",
        "#include <algorithm>",
        "#include <iterator>",
        "",
        "namespace {",
        "",
    ]
    strike_names: list[str] = []
    bitmap_total = 0
    bitmap_sizes: list[int] = []
    for pixel_size in INPUT_SIZES:
        font = ImageFont.truetype(str(font_path), pixel_size)
        missing = font_signature(font, chr(0x10FFFF))
        stem = f"kChineseInput{pixel_size}"
        glyph_lines: list[str] = []
        bitmap = bytearray()
        ascent = 0
        descent = 0
        for character in characters:
            if character == MISSING_GLYPH_MARKER:
                glyph_metrics = rasterize_missing_marker(pixel_size)
            elif ord(character) > 0x7F and font_signature(font, character) == missing:
                raise ValueError(f"font is missing U+{ord(character):04X}")
            else:
                glyph_metrics = rasterize(font, character, threshold)
            width, height, bearing_x, bearing_y, advance, glyph_bitmap = glyph_metrics
            offset = len(bitmap)
            bitmap.extend(glyph_bitmap)
            ascent = max(ascent, -bearing_y)
            descent = max(descent, bearing_y + height)
            glyph_lines.append(
                f"    {{0x{ord(character):04X}U, {offset}U, {width}U, {height}U, "
                f"{bearing_x}, {bearing_y}, {advance}U}},"
            )
        bitmap_total += len(bitmap)
        bitmap_sizes.append(len(bitmap))
        lines.append(f"constexpr ChineseFontGlyph {stem}Glyphs[] = {{")
        lines.extend(glyph_lines)
        lines.extend(["};", ""])
        lines.append(f"constexpr uint8_t {stem}Bitmap[] = {{")
        lines.extend(cpp_bytes(bytes(bitmap)))
        lines.extend(["};", ""])
        strike_name = f"{stem}Strike"
        lines.append(
            f"constexpr ChineseFontStrike {strike_name} = "
            f"{{{pixel_size}U, {ascent}U, {descent}U, {stem}Glyphs, "
            f"std::size({stem}Glyphs), {stem}Bitmap}};"
        )
        lines.append("")
        strike_names.append(strike_name)
    resource_bytes = len(characters) * GLYPH_STRUCT_BYTES * len(INPUT_SIZES) + bitmap_total
    lines.extend(
        [
            "constexpr const ChineseFontStrike *kChineseInputStrikes[] = {",
            *(f"    &{name}," for name in strike_names),
            "};",
            "",
            "}  // namespace",
            "",
            "const ChineseFontStrike &chinese_input_font_strike(uint8_t pixel_size)",
            "{",
            "    const ChineseFontStrike *best = kChineseInputStrikes[0];",
            "    unsigned best_distance = 255U;",
            "    for (const ChineseFontStrike *strike : kChineseInputStrikes) {",
            "        const unsigned size = strike->pixel_size;",
            "        const unsigned distance = size > pixel_size ? size - pixel_size",
            "                                                     : pixel_size - size;",
            "        if (distance < best_distance) {",
            "            best = strike;",
            "            best_distance = distance;",
            "        }",
            "    }",
            "    return *best;",
            "}",
            "",
            "const ChineseFontGlyph *chinese_input_font_glyph(",
            "    const ChineseFontStrike &strike, uint32_t codepoint)",
            "{",
            "    const auto found = std::lower_bound(",
            "        strike.glyphs, strike.glyphs + strike.glyph_count, codepoint,",
            "        [](const ChineseFontGlyph &glyph, uint32_t value) {",
            "            return glyph.codepoint < value;",
            "        });",
            "    return found != strike.glyphs + strike.glyph_count &&",
            "                   found->codepoint == codepoint",
            "               ? found",
            "               : nullptr;",
            "}",
            "",
            "const ChineseFontGlyph *chinese_input_font_resolve_glyph(",
            "    const ChineseFontStrike &strike, uint32_t codepoint)",
            "{",
            "    const ChineseFontGlyph *glyph =",
            "        chinese_input_font_glyph(strike, codepoint);",
            "    return glyph != nullptr",
            "               ? glyph",
            "               : chinese_input_font_glyph(",
            "                     strike, kChineseInputMissingGlyphCodepoint);",
            "}",
            "",
            "size_t chinese_input_font_glyph_count()",
            "{",
            f"    return {len(characters)}U;",
            "}",
            "",
            "size_t chinese_input_font_resource_bytes()",
            "{",
            f"    return {resource_bytes}U;",
            "}",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"Chinese input font generated: glyphs={len(characters)} "
        f"sizes={','.join(map(str, INPUT_SIZES))} "
        f"bitmap_bytes={','.join(map(str, bitmap_sizes))} "
        f"bitmap_total={bitmap_total} "
        f"resource_bytes={resource_bytes} output={output}"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--font",
        type=Path,
        default=Path("tools/.cache/NotoSansSC-Medium.otf"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/ui/assets/chinese_input_font_assets.cpp"),
    )
    parser.add_argument("--threshold", type=int, default=144)
    args = parser.parse_args()
    if not 0 <= args.threshold <= 255:
        parser.error("--threshold must be between 0 and 255")
    generate(args.font, args.output, args.threshold)


if __name__ == "__main__":
    main()
