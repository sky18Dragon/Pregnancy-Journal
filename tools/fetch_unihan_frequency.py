#!/usr/bin/env python3
"""Fetch and extract the pinned Unihan frequency buckets used by the IME."""

from __future__ import annotations

import argparse
import hashlib
import re
import urllib.request
import zipfile
from collections import Counter
from pathlib import Path


UNIHAN_VERSION = "15.1.0"
UNIHAN_URL = f"https://www.unicode.org/Public/{UNIHAN_VERSION}/ucd/Unihan.zip"
UNIHAN_SHA256 = "a0226610e324bcf784ac380e11f4cbf533ee1e6b3d028b0991bf8c0dc3f85853"
MEMBER_NAME = "Unihan_DictionaryLikeData.txt"
FREQUENCY_PATTERN = re.compile(r"^U\+([0-9A-F]+)\tkFrequency\t([1-5])$")


def gb2312_level1_codepoints() -> set[int]:
    codepoints: set[int] = set()
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                character = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            codepoints.add(ord(character))
    if len(codepoints) != 3755:
        raise ValueError(f"unexpected GB2312 Level-1 size: {len(codepoints)}")
    return codepoints


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def download(archive: Path) -> None:
    archive.parent.mkdir(parents=True, exist_ok=True)
    temporary = archive.with_suffix(archive.suffix + ".tmp")
    try:
        with urllib.request.urlopen(UNIHAN_URL, timeout=60) as response, temporary.open(
            "wb"
        ) as output:
            while chunk := response.read(1024 * 1024):
                output.write(chunk)
        temporary.replace(archive)
    finally:
        temporary.unlink(missing_ok=True)


def extract(archive: Path, output: Path) -> None:
    actual_sha256 = sha256(archive)
    if actual_sha256 != UNIHAN_SHA256:
        raise ValueError(f"Unihan SHA-256 mismatch: {actual_sha256}")

    target = gb2312_level1_codepoints()
    frequency: dict[int, int] = {}
    with zipfile.ZipFile(archive) as source:
        for line in source.read(MEMBER_NAME).decode("utf-8").splitlines():
            match = FREQUENCY_PATTERN.match(line)
            if match is None:
                continue
            codepoint = int(match.group(1), 16)
            if codepoint in target:
                frequency[codepoint] = int(match.group(2))

    distribution = Counter(frequency.values())
    if len(frequency) != 3171 or distribution != {1: 93, 2: 374, 3: 460, 4: 888, 5: 1356}:
        raise ValueError(
            f"unexpected filtered kFrequency data: count={len(frequency)} "
            f"distribution={dict(sorted(distribution.items()))}"
        )

    lines = [
        "# Generated by tools/fetch_unihan_frequency.py. Do not edit.",
        f"# Source: {UNIHAN_URL}",
        f"# Source archive SHA-256: {UNIHAN_SHA256}",
        "# Property: kFrequency (1 is the most frequent bucket; 5 is the least).",
        "# Filter: GB2312 Level-1 characters only. Missing characters are unranked.",
    ]
    lines.extend(f"U+{codepoint:04X}\t{frequency[codepoint]}" for codepoint in sorted(frequency))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"verified {archive} sha256={UNIHAN_SHA256}; "
        f"wrote {output} entries={len(frequency)} "
        f"distribution={dict(sorted(distribution.items()))}"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--archive",
        type=Path,
        default=Path("tools/.cache/Unihan-15.1.0.zip"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("third_party/unicode-unihan/kFrequency-gb2312-level1.txt"),
    )
    parser.add_argument(
        "--no-download",
        action="store_true",
        help="require --archive to exist instead of downloading it",
    )
    args = parser.parse_args()
    if not args.archive.exists():
        if args.no_download:
            raise FileNotFoundError(args.archive)
        download(args.archive)
    extract(args.archive, args.output)


if __name__ == "__main__":
    main()
